#!/usr/bin/env bash
# Stops the KDE Plasma lock screen from fighting itself over the fingerprint
# reader.
#
# Plasma's lock screen runs two PAM conversations at once: "kde" for the
# password and "kde-fingerprint" for the finger. After
# `pam-auth-update --enable fprintd` the password conversation also starts
# with pam_fprintd (through common-auth), so both try to claim the one reader.
# Whichever loses times out, and the lock screen shows stray "place your
# finger" / "verification timed out" messages or stops reacting to the finger.
#
# This writes /etc/pam.d/kde: the distribution's /usr/lib/pam.d/kde with the
# common-auth include replaced by the same lines minus pam_fprintd.
#
# Second problem, same script: kde-fingerprint runs pam_kwallet5 after the
# finger matched. If you logged in by finger after boot, no password was ever
# typed, the wallet module asks for one inside a conversation that cannot
# answer, and the fingerprint unlock never completes ("pam_kwallet5: Couldn't
# get password (it is empty)" in the journal). A fingerprint cannot open a
# wallet anyway, so /etc/pam.d/kde-fingerprint is written as the
# distribution's file without the pam_kwallet5 lines.
#
# Only the lock screen changes; sudo and the login screen do not.
#
#   sudo scripts/kde-lockscreen-pam.sh           # install
#   sudo scripts/kde-lockscreen-pam.sh --remove  # undo
#
# If the lock screen ever refuses your password after this, switch to a text
# console (Ctrl+Alt+F3), log in and run it with --remove.

set -euo pipefail

VENDOR=/usr/lib/pam.d/kde
COMMON=/etc/pam.d/common-auth
TARGET=/etc/pam.d/kde
FP_VENDOR=/usr/lib/pam.d/kde-fingerprint
FP_TARGET=/etc/pam.d/kde-fingerprint
MARKER="# Generated by kde-lockscreen-pam.sh"

fail() { echo "ERROR: $*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || fail "Run with sudo."

if [ "${1:-}" = "--remove" ]; then
    for file in "$TARGET" "$FP_TARGET"; do
        if [ -f "$file" ] && grep -qF "$MARKER" "$file"; then
            rm -f "$file"
            echo "Removed $file; the lock screen uses the file in /usr/lib/pam.d again."
        elif [ -f "$file" ]; then
            echo "$file was not created by this script; left alone."
        fi
    done
    exit 0
fi

[ -f "$VENDOR" ] || fail "$VENDOR not found. Is this Plasma 6 with kscreenlocker's PAM files?"
[ -f "$FP_VENDOR" ] || fail "$FP_VENDOR not found; this lock screen has no separate fingerprint path."
for file in "$TARGET" "$FP_TARGET"; do
    if [ -f "$file" ] && ! grep -qF "$MARKER" "$file"; then
        fail "$file exists and was not created by this script. Not overwriting it."
    fi
done

# --- fingerprint path: drop pam_kwallet5 -------------------------------------
grep -q 'pam_fprintd' "$FP_VENDOR" || fail "$FP_VENDOR does not use pam_fprintd; not touching it."
fp_tmp="$(mktemp)"
{
    echo "$MARKER on $(date -I)."
    echo "# $FP_VENDOR without pam_kwallet5. Remove with --remove."
    grep -v 'pam_kwallet5' "$FP_VENDOR"
} > "$fp_tmp"
grep -q 'pam_fprintd' "$fp_tmp" || { rm -f "$fp_tmp"; fail "Generated fingerprint file lost pam_fprintd."; }
install -m 0644 -o root -g root "$fp_tmp" "$FP_TARGET"
rm -f "$fp_tmp"
echo "Wrote $FP_TARGET."

# --- password path: drop pam_fprintd ------------------------------------------
grep -q '^@include[[:space:]]\+common-auth' "$VENDOR" || fail "$VENDOR does not include common-auth; nothing to do."

# Active (non-comment) auth lines of common-auth.
mapfile -t auth_lines < <(grep -E '^[[:space:]]*auth[[:space:]]' "$COMMON")
[ "${#auth_lines[@]}" -gt 0 ] || fail "No auth lines in $COMMON."

if ! printf '%s\n' "${auth_lines[@]}" | grep -q pam_fprintd; then
    echo "pam_fprintd is not in $COMMON, so there is no conflict to fix."
    exit 0
fi
# The jump counts ([success=N]) of the other lines only stay correct when the
# fingerprint line is the first one, which is where pam-auth-update puts it.
case "${auth_lines[0]}" in
    *pam_fprintd*) ;;
    *) fail "pam_fprintd is not the first auth line in $COMMON; edit $TARGET by hand." ;;
esac
password_lines="$(printf '%s\n' "${auth_lines[@]:1}")"
echo "$password_lines" | grep -q 'pam_unix' || fail "No pam_unix line left; refusing to write a file that cannot check passwords."

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
    echo "$MARKER on $(date -I)."
    echo "# $VENDOR with common-auth inlined, minus pam_fprintd."
    echo "# Re-run the script after changing $COMMON. Remove with --remove."
    while IFS= read -r line; do
        if [[ "$line" =~ ^@include[[:space:]]+common-auth ]]; then
            echo "$password_lines"
        else
            echo "$line"
        fi
    done < "$VENDOR"
} > "$tmp"

install -m 0644 -o root -g root "$tmp" "$TARGET"
echo "Wrote $TARGET. Lock the screen (Meta+L) and test both the finger and the password."
